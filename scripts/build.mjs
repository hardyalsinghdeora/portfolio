// Builds the deployable site into dist/. Node port of scripts/build.ps1, with the same output:
//   1. knowledge/profile.json -> src/knowledge.js (ES module used by the Worker and the tests)
//   2. keeps the FACTS copy inside public/index.html in sync with profile.json
//   3. bundles src/*.js into a single dist/_worker.js and copies public/ next to it
// Usage: node scripts/build.mjs
import { readFileSync, writeFileSync, rmSync, mkdirSync, cpSync, readdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const write = (p, s) => writeFileSync(join(root, p), s, "utf8");

const profileJson = read("knowledge/profile.json").trim();
JSON.parse(profileJson); // fail fast on invalid JSON

// 1. src/knowledge.js
write("src/knowledge.js",
  `// Generated by scripts/build.ps1 from knowledge/profile.json. Do not edit by hand.\nexport const PROFILE = ${profileJson};\n`);

// 2. FACTS string in the page (used when the page runs inside a Claude artifact).
// "<" is escaped so no profile text can close the surrounding <script>.
const literal = JSON.stringify(profileJson).replace(/</g, "\\u003c");
let index = read("public/index.html");
const re = /var FACTS = ".*?(?<!\\)";/;
if (!re.test(index)) throw new Error("var FACTS not found in public/index.html");
index = index.replace(re, () => `var FACTS = ${literal};`);
write("public/index.html", index);

// 3. dist/
const dist = join(root, "dist");
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist);
cpSync(join(root, "public"), dist, { recursive: true });

const out = ["// Generated by scripts/build.ps1 from src/. Edit the modules in src/, then rebuild."];
for (const name of ["knowledge.js", "rag.js", "agent.js", "worker.js"]) {
  out.push("", `// ---- src/${name} ----`);
  for (let line of read(`src/${name}`).split(/\r?\n/)) {
    if (/^import .+ from ".+";\s*$/.test(line)) continue;
    if (!/^export default/.test(line)) line = line.replace(/^export (const|let|function|async function) /, "$1 ");
    out.push(line);
  }
}
const bundle = out.join("\n");
if (/^\s*import /m.test(bundle)) throw new Error("unbundled import left in _worker.js");
// Modules share one scope once concatenated, so top-level names must be unique across src/.
const names = [...bundle.matchAll(/^(?:const|let|var|function|async function|class) ([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);
const dupes = [...new Set(names.filter((n, i) => names.indexOf(n) !== i))];
if (dupes.length) throw new Error("duplicate top-level names across src/ modules: " + dupes.join(", "));
writeFileSync(join(dist, "_worker.js"), bundle, "utf8");

console.log("built dist/: " + readdirSync(dist).filter((f) => statSync(join(dist, f)).isFile())
  .map((f) => `${f} (${Math.round(statSync(join(dist, f)).size / 1024)}KB)`).join(", "));
