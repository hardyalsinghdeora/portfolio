# Builds the deployable site into dist/ (no Node needed).
#   1. knowledge/profile.json -> src/knowledge.js (ES module used by the Worker and the tests)
#   2. bundles src/*.js into a single dist/_worker.js and copies public/ next to it
# Usage: powershell -ExecutionPolicy Bypass -File scripts/build.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$utf8 = New-Object System.Text.UTF8Encoding($false)

$profileJson = [IO.File]::ReadAllText((Join-Path $root 'knowledge/profile.json'), $utf8)
$null = $profileJson | ConvertFrom-Json   # fail fast on invalid JSON

# 1. src/knowledge.js
$knowledge = "// Generated by scripts/build.ps1 from knowledge/profile.json. Do not edit by hand.`nexport const PROFILE = $($profileJson.Trim());`n"
[IO.File]::WriteAllText((Join-Path $root 'src/knowledge.js'), $knowledge, $utf8)

# 2. dist/
$dist = Join-Path $root 'dist'
if (Test-Path $dist) { Remove-Item $dist -Recurse -Force }
New-Item -ItemType Directory $dist | Out-Null
Copy-Item (Join-Path $root 'public/*') $dist -Recurse

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by scripts/build.ps1 from src/. Edit the modules in src/, then rebuild.')
foreach ($name in 'knowledge.js', 'rag.js', 'agent.js', 'providers.js', 'guard.js', 'fit.js', 'worker.js') {
  [void]$sb.AppendLine("`n// ---- src/$name ----")
  foreach ($line in [IO.File]::ReadAllLines((Join-Path $root "src/$name"), $utf8)) {
    if ($line -match '^import .+ from ".+";\s*$') { continue }
    if ($line -notmatch '^export default') { $line = $line -replace '^export (const|let|function|async function) ', '$1 ' }
    [void]$sb.AppendLine($line)
  }
}
$bundle = $sb.ToString()
if ($bundle -match '(?m)^\s*import ') { throw 'unbundled import left in _worker.js' }
# Modules share one scope once concatenated, so top-level names must be unique across src/.
$names = [regex]::Matches($bundle, '(?m)^(?:const|let|var|function|async function|class) ([A-Za-z_$][\w$]*)') | ForEach-Object { $_.Groups[1].Value }
$dupes = $names | Group-Object | Where-Object Count -gt 1 | ForEach-Object Name
if ($dupes) { throw "duplicate top-level names across src/ modules: $($dupes -join ', ')" }
[IO.File]::WriteAllText((Join-Path $dist '_worker.js'), $bundle, $utf8)

"built dist/: " + ((Get-ChildItem $dist -File | ForEach-Object { "$($_.Name) ($([math]::Round($_.Length/1KB))KB)" }) -join ', ')
