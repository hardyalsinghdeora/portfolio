// Paste-ready LinkedIn and Naukri text, generated from knowledge/profile.json so the job sites
// say what the portfolio says. scripts/build.mjs writes the result to docs/listings.md and fails
// the build if any field is over the site's character limit. Plain ES module with no imports,
// so tests/index.html can check it too.

const SITE = "https://hardyalsinghdeora.pages.dev/";
const RESUME_PDF = SITE + "resume-agentic-ai.pdf";

// Character limits as the sites enforce them (Naukri's summary box is about 1,000).
export const LIMITS = {
  linkedin_headline: 220,
  linkedin_about: 2600,
  naukri_headline: 250,
  naukri_summary: 1000,
};

// Short, searchable skill names recruiters filter on. A name is only emitted when its pattern
// matches the profile's own skills or AI sections, so this list can't claim anything new.
const KEYWORDS = [
  ["Agentic AI", /agentic/i],
  ["LLM Agents", /\bagents?\b/i],
  ["Generative AI", /\bLLM\b|gen ai|generative/i],
  ["Retrieval-Augmented Generation (RAG)", /retrieval-augmented/i],
  ["Model Context Protocol (MCP)", /model context protocol|\bMCP\b/],
  ["Function Calling", /function calling/i],
  ["Prompt Engineering", /prompt and context engineering/i],
  ["LLM Evaluation", /retrieval evaluation|eval set/i],
  ["Anthropic Claude", /anthropic claude/i],
  ["Google Gemini", /gemini/i],
  ["Ollama", /ollama/i],
  ["System Design", /system design/i],
  ["Software Architecture", /architecture/i],
  ["Microservices", /microservices/i],
  ["Distributed Systems", /distributed systems/i],
  ["API Design", /api design/i],
  ["TypeScript", /typescript/i],
  ["Node.js", /node\.js/i],
  ["Python", /\bpython\b/i],
  ["PostgreSQL", /postgresql/i],
  ["AWS", /\bAWS\b/],
  ["Cloudflare Workers", /cloudflare workers/i],
  ["Docker", /docker/i],
  ["Data Migration", /data migration/i],
  ["Technical Leadership", /technical leadership/i],
];

const cut = (s, n) => s.replace(/\s*\([^)]*\)/g, "").trim().slice(0, n);
const sentences = (s) => String(s).match(/[^.!?]+[.!?]+(\s|$)/g) || [String(s)];

// Whole sentences, in order, as long as they fit.
function fit(parts, limit) {
  let out = "";
  for (const s of parts.flatMap(sentences)) {
    const next = (out ? out + " " : "") + s.trim();
    if (next.length > limit) break;
    out = next;
  }
  return out;
}

export function buildListings(p) {
  const id = p.identity || {};
  // The summary is written for the portfolio page; on a job site "this portfolio" means nothing.
  const summary = String(p.summary || "").replace(/\(this portfolio\)/g, "(my portfolio site)");
  const av = p.availability || {};
  const evidence = JSON.stringify([p.skills, p.agentic_ai, p.summary]);
  const skills = KEYWORDS.filter(([, re]) => re.test(evidence)).map(([name]) => name);
  const listed = new Set(((p.linkedin && p.linkedin.listed_skills) || []).map((s) => s.toLowerCase()));
  const link = (ref) => `${SITE}?ref=${ref}`;
  const metrics = (p.headline_metrics || []).slice(0, 4).map((m) => `• ${m.value} ${m.label}`);

  const fields = {
    linkedin_headline: id.headline,
    linkedin_about: [
      id.one_liner,
      summary,
      "In numbers:\n" + metrics.join("\n"),
      `Ask my portfolio agent anything about my work (it answers from my profile and shows its sources): ${link("linkedin")}`,
      `Decision records: ${SITE}case/db-migration and ${SITE}case/php-to-node`,
      `Open to ${(p.targeting && p.targeting.roles || []).slice(0, 2).join(" and ")} roles. Notice period ${av.notice_period}. Email: ${p.contact && p.contact.email_primary}`,
    ].join("\n\n"),
    naukri_headline: `${id.headline} | Notice: ${av.notice_period}`,
    naukri_summary: fit([id.one_liner, summary], LIMITS.naukri_summary),
  };

  const over = Object.entries(LIMITS)
    .filter(([k, n]) => !fields[k] || fields[k].length > n)
    .map(([k, n]) => `${k} is ${fields[k] ? fields[k].length : 0} characters (limit ${n})`);

  return {
    fields,
    skills,
    skillsToAdd: skills.filter((s) => !listed.has(s.toLowerCase())),
    openToWorkTitles: ((p.targeting && p.targeting.roles) || []).slice(0, 5).map((r) => cut(r, 60)),
    links: {
      linkedin: link("linkedin"),
      naukri: link("naukri"),
      resume_pdf: RESUME_PDF,
      github: p.contact && p.contact.github,
      case_studies: "https://github.com/hardyalsinghdeora/case-studies",
    },
    over,
  };
}

export function listingsMarkdown(p) {
  const l = buildListings(p);
  const block = (k) => `\`\`\`text\n${l.fields[k]}\n\`\`\`\n${l.fields[k].length} / ${LIMITS[k]} characters`;
  return `<!-- Generated by scripts/build.mjs from knowledge/profile.json. Edit the profile, then run npm test. -->
# LinkedIn and Naukri text

Paste these into the job sites so they say what the portfolio says. Regenerated on every build,
from profile data updated ${p.meta && p.meta.updated}.

## LinkedIn

**Headline**

${block("linkedin_headline")}

**About**

${block("linkedin_about")}

**Skills to add** (in the profile, missing from LinkedIn's listed skills)

${l.skillsToAdd.map((s) => `- ${s}`).join("\n") || "- none: LinkedIn already lists them all"}

**Open to Work job titles** (LinkedIn allows five; pick the nearest suggestion it offers)

${l.openToWorkTitles.map((t) => `- ${t}`).join("\n")}

**Contact info → Website** and the **Featured** section: ${l.links.linkedin}

## Naukri

**Resume headline**

${block("naukri_headline")}

**Profile summary**

${block("naukri_summary")}

**Key skills**

${l.skills.join(", ")}

**Online profile / Projects**

- Portfolio: ${l.links.naukri}
- GitHub: ${l.links.github}
- Case studies: ${l.links.case_studies}

**Resume file:** download ${l.links.resume_pdf} and upload it (single column, parses cleanly).

## Tracking

The \`?ref=linkedin\` and \`?ref=naukri\` links let the site count visits and questions per source
(see "Visit sources" in the README). Use them everywhere you paste the portfolio link.
`;
}
